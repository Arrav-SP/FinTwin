ALTER TABLE experiment_runs ADD COLUMN IF NOT EXISTS error_rate NUMERIC(10,6);

CREATE TABLE IF NOT EXISTS workload_events (
    event_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    experiment_id UUID NOT NULL REFERENCES experiment_runs(experiment_id) ON DELETE CASCADE,
    operation VARCHAR(40) NOT NULL,
    latency_ms NUMERIC(18, 4) NOT NULL CHECK (latency_ms >= 0),
    success BOOLEAN NOT NULL,
    error_message TEXT,
    recorded_at TIMESTAMPTZ NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_workload_events_experiment_id ON workload_events(experiment_id);
CREATE INDEX IF NOT EXISTS idx_workload_events_recorded_at ON workload_events(recorded_at);

CREATE TABLE IF NOT EXISTS telemetry_samples (
    telemetry_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    experiment_id UUID NOT NULL REFERENCES experiment_runs(experiment_id) ON DELETE CASCADE,
    sample_kind VARCHAR(10) NOT NULL CHECK (sample_kind IN ('INITIAL','SAMPLE','FINAL')),
    captured_at TIMESTAMPTZ NOT NULL, active_connections INTEGER, idle_connections INTEGER,
    waiting_connections INTEGER, max_connections INTEGER, xact_commit BIGINT, xact_rollback BIGINT,
    blks_read BIGINT, blks_hit BIGINT, tup_inserted BIGINT, tup_updated BIGINT, tup_deleted BIGINT,
    deadlocks BIGINT, lock_count BIGINT, lock_wait_count BIGINT, blocked_sessions INTEGER,
    database_size_bytes BIGINT, cache_hit_ratio NUMERIC(10,4), host_cpu_percent NUMERIC(10,4), host_memory_percent NUMERIC(10,4)
);
CREATE INDEX IF NOT EXISTS idx_telemetry_samples_experiment_time ON telemetry_samples(experiment_id, captured_at);

CREATE TABLE IF NOT EXISTS experiment_summaries (
    experiment_id UUID PRIMARY KEY REFERENCES experiment_runs(experiment_id) ON DELETE CASCADE,
    error_rate NUMERIC(10,6), p50_latency_ms NUMERIC(18,4), p95_latency_ms NUMERIC(18,4), p99_latency_ms NUMERIC(18,4),
    active_connections_max INTEGER, blocked_sessions_max INTEGER, lock_wait_count_max BIGINT,
    db_xact_commit_delta BIGINT, db_xact_rollback_delta BIGINT, db_deadlocks_delta BIGINT, db_cache_hit_ratio NUMERIC(10,4),
    host_cpu_avg_percent NUMERIC(10,4), host_memory_avg_percent NUMERIC(10,4), db_size_before_bytes BIGINT, db_size_after_bytes BIGINT,
    telemetry_sample_count INTEGER NOT NULL DEFAULT 0, telemetry_error_count INTEGER NOT NULL DEFAULT 0, generated_at TIMESTAMPTZ NOT NULL
);
